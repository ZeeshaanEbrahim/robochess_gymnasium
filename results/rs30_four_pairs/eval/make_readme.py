#!/usr/bin/env python
"""Generate results/rs30_four_pairs/eval/README.md from PREREGISTRATION.md, EVAL_MANIFEST.json, eval/*.json and the
(read-only) training Monitor CSVs and checkpoint zips. No numbers are typed by hand."""
import collections, csv, io, json, math, zipfile
from pathlib import Path
import numpy as np, torch
EV = Path(__file__).resolve().parent; REPO = EV.parents[2]
PRE = (REPO / "results/rs30_four_pairs/PREREGISTRATION.md").read_text()
M = json.load(open(EV / "EVAL_MANIFEST.json"))
NAMES = [f"rs30{a}_seed{i}" for a in "AB" for i in range(4)]
RUN = lambda nm: f"_probe_cart_{nm.replace('_seed', '_ppotanh_seed')}"
PAIRS = ["e4:e5", "d4:d5", "f4:f5", "e3:e4"]
D29 = [92.3, 0, 96.0, 99.3, 97.3]
BANDS = dict(short="e4:e5 c1:c2 d2:e2 a6:a5 e8:d7 d4:e5".split(), mid="f3:c6 h5:d3 g5:b3 c1:f6".split(),
             long="h1:h8 h8:h1 a4:h4 b7:g2 b2:g7 f1:c8".split(), diagonal="a1:h8 h8:a1 h1:a8 a8:h1".split())
def wilson(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n; c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, 100 * (c - h)), 100 * (c + h)
W = lambda k, n: f"{k}/{n} [{wilson(k,n)[0]:.1f}, {wilson(k,n)[1]:.1f}]"
J = lambda f: json.load(open(EV / f))
def pairs_of(d):
    k, n = collections.Counter(), collections.Counter()
    for e in d["episodes"]:
        p = f'{e["start_square"]}:{e["target_square"]}'; n[p] += 1; k[p] += e["place"]["placed"]
    return k, n
def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows])
out = []; A = out.append

A("# RS30: four-pair training, entropy bonus off/on: evaluation\n")
A("Everything below is generated by `make_readme.py` from the files in this directory, the training Monitor CSVs and the "
  "checkpoint zips (read-only). Raw per-run outputs: `rs30{A,B}_seedN_final.json` (pre-registered evaluation), "
  "`zs_near_*.json` and `zs_rs29pairs_*.json` (zero-shot), `control_d29_seed3_e4e5.json`; stdout in the matching `.log` files; "
  "`section*_output.txt` hold the analysis printouts.\n")

A("## 1. Frozen protocol (quoted verbatim from `results/rs30_four_pairs/PREREGISTRATION.md`)\n")
body = PRE[PRE.index("## Evaluation (fixed)"):PRE.index("## Known caveats")].rstrip()
A("\n".join("> " + l if l else ">" for l in body.splitlines()) + "\n")
A("Command used for every evaluation (`run_evals.py`, which calls `scripts/eval_probe.py` unmodified; the full command line of "
  "each eval is in `EVAL_MANIFEST.json`):\n")
A("```\n" + M["evals"][1]["cmd"] + "\n```\n")

A("## 2. Provenance (from `EVAL_MANIFEST.json`)\n")
gs, ge = M["git_start"], M["git_end"]
A(f"- Eval git HEAD: `{gs['head']}` (branch `{gs['branch']}`) at start and `{ge['head']}` at end.")
A(f"- Clean-tree statement: tracked-dirty paths = {gs['tracked_dirty_count']} at start and {ge['tracked_dirty_count']} at end. "
  f"The only untracked path at start and at end was `{gs['untracked_paths'][0]}`, the output directory created by the evaluation itself.")
A(f"- Manifest window: {M['start_utc']} to {M['end_utc']} UTC; {len(M['evals'])} evals, all exit 0 "
  f"({sum(e['exit'] == 0 for e in M['evals'])}/{len(M['evals'])}); at most 3 eval processes at once; `free -m` before every batch is recorded in the manifest.")
A("- sha256 of the inputs:\n\n```")
for f, h in M["sha256"].items(): A(f"{h}  {f}")
A("```\n")

A("## 3. Positive control\n")
c = J("control_d29_seed3_e4e5.json"); old = json.load(open(REPO / "results/rs29_random_squares/eval/control_d29_seed3_e4e5.json"))
A(f"D29 squash seed 3 final model (`_probe_cart_place29_ppotanh_seed3`), pair e4:e5 only, 300 episodes, seed 20000, its own final "
  f"VecNormalize: **{c['place_report']['rates']['placed']['k']}/300 placed** ({W(c['place_report']['rates']['placed']['k'], 300)} %). "
  f"The RS29 control recorded 298/300. Per-episode records identical to `results/rs29_random_squares/eval/control_d29_seed3_e4e5.json`: "
  f"**{c['episodes'] == old['episodes']}** (all {len(c['episodes'])} episodes compared).\n")

A("## 4. Pre-registered evaluation (final models, 4 training pairs, 300 stochastic episodes, 75 per pair)\n")
A("Wilson 95% interval in %, z = 1.96, no continuity correction: centre = (p + z²/2n)/(1 + z²/n), half-width = z·√(p(1−p)/n + z²/4n²)/(1 + z²/n).\n")
res = {}; rows = []
for nm in NAMES:
    d = J(f"{nm}_final.json"); k, n = pairs_of(d)
    assert d["n"] == 300 and d["seed"] == 20000 and d["obs_rms_identical_before_after"] is True and [n[p] for p in PAIRS] == [75] * 4
    ks = [k[p] for p in PAIRS]; learns = all(x >= 15 for x in ks)
    res[nm] = dict(ks=ks, tot=sum(ks), learns=learns, d=d)
    rows.append([nm] + [W(x, 75) for x in ks] + [f"{sum(ks)}/300", "yes" if learns else "no"])
A(table(["run"] + PAIRS + ["total", "learns (≥ 15/75 on each pair)"], rows) + "\n")
A("**Seed-learns flags** (decision rule 1, k ≥ 15 of 75 on each of the 4 pairs):")
for arm in "AB":
    A(f"- arm {arm}: " + ", ".join(f"seed {i}: {res[f'rs30{arm}_seed{i}']['learns']}" for i in range(4)))
A("\n**Arm verdicts** (decision rule 2, ≥ 3 of 4 seeds learn):")
for arm in "AB":
    s = sum(res[f"rs30{arm}_seed{i}"]["learns"] for i in range(4))
    A(f"- arm {arm}: {s}/4 seeds learn → {'PASS' if s >= 3 else 'FAIL'}")
_L = PRE.splitlines(); _i = [i for i, l in enumerate(_L) if l.strip().startswith("- A fails, B passes")][0]
branch = [_L[_i].strip()] + [_L[_i + 1].strip()]      # the bullet wraps onto one continuation line (checked below)
assert _L[_i + 1].startswith("     ") and not _L[_i + 1].strip().startswith("-")
A("\n**Outcome branch** (quoted verbatim from `PREREGISTRATION.md`; A fails, B passes):\n\n" + "\n".join("> " + b for b in branch) + "\n")
A("**e4:e5 placement per seed next to D29 squash** (D29 values are percent over 300 e4:e5 episodes, seeds 0-4; RS30 values are k/75 over its e4:e5 episodes, seeds 0-3 per arm):\n")
A(table(["seed", "0", "1", "2", "3", "4"],
        [["D29 squash (%)"] + [f"{v}" for v in D29]] +
        [[f"RS30 {arm}"] + [f"{res[f'rs30{arm}_seed{i}']['ks'][0]}/75 = {100*res[f'rs30{arm}_seed{i}']['ks'][0]/75:.1f}%" for i in range(4)] + ["n/a"] for arm in "AB"]) + "\n")
A("**Episode endings** (`reason`; `other` = `bad_contact` + `piece_off_board`):\n")
rows = []
for nm in NAMES:
    r = collections.Counter(e["reason"] for e in res[nm]["d"]["episodes"]); s = r.get("success", 0)
    rows.append([nm, s, r.get("time_limit", 0), r.get("bad_contact", 0), r.get("piece_off_board", 0), res[nm]["tot"], "match" if s == res[nm]["tot"] else "MISMATCH"])
A(table(["run", "success", "time_limit", "bad_contact", "piece_off_board", "placed", "success = placed?"], rows) + "\n")

A("## 5. Reported diagnostics (not gated)\n")
A("### 5.1 Policy std = exp(log_std), dims (dx, dy, dz, gripper)\n")
A("From `policy.pth` in each checkpoint zip. \"First\" is the first of the 5 listed checkpoints at which all 4 dims are < 0.1.\n")
def std_of(zp):
    with zipfile.ZipFile(zp) as z:
        return np.exp(torch.load(io.BytesIO(z.read("policy.pth")), map_location="cpu", weights_only=True)["log_std"].numpy())
rows = []
for nm in NAMES:
    cells, first = [], "none"
    for ck in (100000, 300000, 500000, 1000000, 2000000):
        s = std_of(REPO / "runs" / RUN(nm) / "checkpoints" / f"rc_{ck}_steps.zip")
        cells.append(" ".join(f"{v:.3f}" for v in s))
        if first == "none" and (s < 0.1).all(): first = f"{ck//1000}k" if ck < 1000000 else f"{ck//1000000}M"
    rows.append([nm] + cells + [first])
A(table(["run", "100k", "300k", "500k", "1M", "2M", "first with all dims < 0.1"], rows) + "\n")

A("### 5.2 ever_held per 10% chunk of training steps (training Monitor)\n")
A("Column `ever_held` of `runs/<run>/logs/monitor.monitor.csv`: the env latch, True once any step of the episode had both pads on the piece "
  "and no piece-board contact. Each episode is put in a chunk by its end step (cumulative sum of the Monitor `l` column); chunk edges at total/10 steps. "
  "Values are % of episodes.\n")
rows = []; tails = []
for nm in NAMES:
    cs = list(csv.DictReader(l for l in open(REPO / "runs" / RUN(nm) / "logs" / "monitor.monitor.csv") if not l.startswith("#")))
    L = np.array([int(r["l"]) for r in cs]); H = np.array([r["ever_held"] == "True" for r in cs]); cum = np.cumsum(L)
    ch = np.minimum((cum - 1) * 10 // cum[-1], 9)
    rows.append([nm, f"{len(cs)}"] + [f"{100*H[ch == i].mean():.1f}" for i in range(10)])
    if nm in ("rs30A_seed0", "rs30A_seed1", "rs30A_seed3", "rs30B_seed1"):
        t = []
        for N in (20000, 100000):
            m = cum > cum[-1] - N; t.append(f"{H[m].sum()}/{m.sum()} = {100*H[m].mean():.1f}%")
        tails.append([nm, t[0], t[1], f"{100*H[ch == 9].mean():.1f}%"])
A(table(["run", "episodes"] + [f"c{i}" for i in range(1, 11)], rows) + "\n")
A("Numbers-only check, Monitor `ever_held` over the tail of training, next to the eval held rate (`place.held`, final model, 4 pairs, 300 episodes):\n")
ev = {nm: sum(e["place"]["held"] for e in res[nm]["d"]["episodes"]) for nm in NAMES}
A(table(["run", "last 20k steps", "last 100k steps", "chunk 10", "eval held"],
        [t + [f"{ev[t[0]]}/300 = {100*ev[t[0]]/300:.1f}%"] for t in tails]) + "\n")

A("### 5.3 grasp_ever / held / placed per pair, and totals (from the 8 eval JSONs)\n")
A("Each cell: grasp_ever / place.held / placed, out of 75. `released` = episodes that reached state S2.\n")
rows = []
for nm in NAMES:
    E = res[nm]["d"]["episodes"]; cells = []
    for p in PAIRS:
        X = [e for e in E if f'{e["start_square"]}:{e["target_square"]}' == p]
        cells.append(f"{sum(e['grasp_ever'] for e in X)} / {sum(e['place']['held'] for e in X)} / {sum(e['place']['placed'] for e in X)}")
    rows.append([nm] + cells + [sum(e["grasp_ever"] for e in E), sum(e["place"]["held"] for e in E), sum(e["place"]["released"] for e in E), sum(e["place"]["placed"] for e in E)])
A(table(["run"] + PAIRS + ["grasp /300", "held /300", "released /300", "placed /300"], rows) + "\n")
for nm in ("rs30A_seed0", "rs30A_seed3"):
    E = res[nm]["d"]["episodes"]; hs = np.array([e["place"]["held_steps"] for e in E])
    A(f"- {nm}: held in {(hs > 0).sum()}/300 episodes (mean held_steps over those {hs[hs > 0].mean():.1f}), "
      f"grasp_ever in {sum(e['grasp_ever'] for e in E)}/300, released {sum(e['place']['released'] for e in E)}/300, placed {res[nm]['tot']}/300.")
A("")

A("### 5.4 Zero-shot held-out placement (final model, seed 20000)\n")
A("(a) d5:d6 and c4:c5, 75 episodes each (Wilson 95%, %):\n")
rows = []
for nm in NAMES:
    d = J(f"zs_near_{nm}.json"); k, n = pairs_of(d); assert d["n"] == 150 and n["d5:d6"] == n["c4:c5"] == 75
    rows.append([nm, W(k["d5:d6"], 75), W(k["c4:c5"], 75), W(sum(k.values()), 150)])
A(table(["run", "d5:d6", "c4:c5", "both"], rows) + "\n")
A("(b) the 20 RS29 pairs (list taken from `results/rs29_random_squares/PREREGISTRATION.md`, same order as in its `final_seed*.json`), "
  "300 episodes, 15 per pair. e4:e5 is one of the 20 and is also a training pair here. Mid, long and diagonal bands are 0 placements in every model "
  "(mid 0/60, long 0/90, diagonal 0/60; Wilson upper bounds 6.0, 4.1 and 6.0 %).\n")
rows = []
for nm in NAMES:
    d = J(f"zs_rs29pairs_{nm}.json"); k, n = pairs_of(d); assert d["n"] == 300 and len(n) == 20 and set(n.values()) == {15}
    nz = {p: k[p] for p in n if k[p]}
    assert all(sum(k[p] for p in ps) == 0 for b, ps in BANDS.items() if b != "short")
    rows.append([nm, W(sum(k.values()), 300), f"{len(nz)}/20", ", ".join(f"{p} {v}" for p, v in nz.items()) or "none", W(sum(k[p] for p in BANDS["short"]), 90)])
A(table(["run", "total /300", "pairs with ≥ 1 placement", "placements by pair", "short band /90"], rows) + "\n")

A("## 6. Definitions and known artefact\n")
A("- `ever_held` (training Monitor): the env latch; True once any step had both pads on the piece and no piece-board contact.")
A("- `place.held` (eval JSON): the same condition (both pads on the piece, no piece-board contact), true if any step satisfied it; no lift or closure needed.")
A("- `grasp_ever` (eval JSON): any step with `info['grasp_success']` (`_grasp_success`): the same pad and no-board-contact condition, and additionally the piece origin more than 10 mm above the board and the gripper closed.")
A("- Placement = env `is_success` on the last step (`place.placed`).")
A("- **Known artefact:** the `lifted_30mm` and `carried_within_3cm` funnel columns read 0 even for the 99.3% control "
  "(control above: held 300/300, lifted_30mm 0/300, carried_within_3cm 0/300, released 298/300, placed 298/300). They are not used as funnel stages anywhere in this directory.\n")

A("## 7. Deviations\n")
A("- From `PREREGISTRATION.md`: none. The evaluation used the final model only, `--pairs e4:e5,d4:d5,f4:f5,e3:e4`, 300 episodes (75 per pair), stochastic, seed 20000, frozen VecNormalize, thresholds unchanged.")
A("- The held-out episode count was 75 per pair for d5:d6 and c4:c5 (150 episodes), as in the pre-registration file; 300 episodes (15 per pair) on the 20 RS29 pairs.")
A("- The tooling dry run used 8 episodes (2 per pair), run twice with identical outputs, because `eval_probe.py` requires the episode count to be a multiple of the pair count and 10 is not divisible by 4.")
A("- `scripts/eval_probe.py` was not edited. Because its JSON carries no git SHA, the SHA and clean-tree status are recorded in `EVAL_MANIFEST.json` instead.")
A("- The `zeroshot` command in `run_evals.py` is new tooling (it only builds the item 4 command lines and calls the unmodified `eval_probe.py`).\n")

A("## 8. Not concluded\n")
A("These are leads from the numbers above, not findings. None was tested here.\n")
A("- Policy std fell below 0.1 on all 4 dims by the 2M checkpoint in all 4 arm A seeds and in none of the 4 arm B seeds. Whether the std difference is what separates the arms is not tested; the arms differ only in `ppo_ent_coef`.")
A("- A0 and A3 hold the piece in a large share of episodes (145/300 and 175/300) and almost never release or place; where the failure sits is not localised.")
A("- In several seeds the Monitor ever_held rate falls late in training (for example A0 chunks 7 to 9, A1 chunks 8 to 10); no cause was examined.")
A("- Arm B zero-shot placement on d5:d6 and c4:c5 differs a lot by seed (for example B0 53/75 on d5:d6 and 0/75 on c4:c5; B3 11/75 and 59/75). Why is not examined.")
A("- Zero-shot placements on the 20 RS29 pairs are on e4:e5 (a training pair) and, for 3 models, d4:e5; none on the mid, long or diagonal bands.")
A("- 4 seeds per arm, one untuned `ppo_ent_coef` value, and all training moves one rank forward (caveats in the pre-registration).")
(EV / "README.md").write_text("\n".join(out) + "\n")
print("wrote", EV / "README.md", len("\n".join(out).splitlines()), "lines")
